import { readFile, mkdir, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { homedir } from "node:os";
import { resolve } from "node:path";
import postcss from "postcss";

// Use the skill's layout engine for figures embedded in existing lessons.
const skill = process.env.ANSWER_HTML_SKILL_DIR || resolve(homedir(), ".codex/skills/answer-me-with-html");
const output = resolve(".local/education-diagrams.html");
await mkdir(resolve(".local"), { recursive: true });
const result = spawnSync(process.execPath, [resolve(skill, "scripts/am.mjs"), "render", resolve("content/education/diagrams.md"), "-o", output, "--no-open"], { encoding: "utf8" });
if (result.error || result.status !== 0) throw new Error(result.error?.message || result.stderr || result.stdout);
process.stdout.write(result.stdout);
process.stderr.write(result.stderr);
const html = await readFile(output, "utf8");
const figures = [...html.matchAll(/<figure class="am-diagram[^\"]*">[\s\S]*?<\/figure>/g)].map(match => match[0]);
if (figures.length !== 3) throw new Error(`Expected three lesson diagrams, got ${figures.length}`);
if (figures.some(figure => /<script\b|\bon\w+=/i.test(figure))) throw new Error("Unexpected executable content in lesson diagrams");
const diagrams = Object.fromEntries(["feedback", "learning", "reinforcement"].map((key, index) => [key, figures[index]]));
const css = postcss.parse([...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map(match => match[1]).join("\n"));
css.walkRules(rule => {
  if (rule.parent.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.map(selector => {
    const trimmed = selector.trim();
    if (/^(html|body|:root)(?=[\s[.:#]|$)/.test(trimmed)) return trimmed.replace(/^(html|body|:root)/, ".education-concept-figure").replaceAll("data-theme", "data-am-theme").replaceAll("data-mode", "data-am-mode");
    return `.education-concept-figure ${trimmed}`;
  });
});
await mkdir(resolve("src/lib/education/generated"), { recursive: true });
await writeFile(resolve("src/lib/education/generated/diagrams.json"), JSON.stringify(diagrams, null, 2) + "\n");
await writeFile(resolve("src/app/education/diagrams.generated.css"), `/* Generated by scripts/build-education-diagrams.mjs. */\n${css.toString()}`);
console.log("Updated three concept diagrams for existing lessons.");
